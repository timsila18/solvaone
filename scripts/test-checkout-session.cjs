const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
const mod = { exports: {} };
const source = fs.readFileSync("src/lib/job-desk/checkout-session.ts", "utf8");
new Function("exports", "require", "module", ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(mod.exports, require, mod);
const { readCheckoutSession, saveCheckoutSession, clearCheckoutSession, paymentPollDelay, paymentPollingFinished } = mod.exports;
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
const session = { token: "a".repeat(64), reference: "TESTONLY" };
saveCheckoutSession(storage, session);
assert.deepEqual(readCheckoutSession(storage), session);
clearCheckoutSession(storage);
assert.equal(readCheckoutSession(storage), null);
storage.setItem("solva-job-desk-checkout", "{broken");
assert.equal(readCheckoutSession(storage), null);
storage.setItem("solva-job-desk-checkout", JSON.stringify({ token: "bad" }));
assert.equal(readCheckoutSession(storage), null);
const denied = { getItem() { throw new Error("SecurityError"); }, setItem() { throw new Error("QuotaExceededError"); }, removeItem() { throw new Error("SecurityError"); } };
assert.equal(readCheckoutSession(denied), null);
assert.doesNotThrow(() => saveCheckoutSession(denied, session));
assert.doesNotThrow(() => clearCheckoutSession(denied));
assert.equal(paymentPollDelay(0), 15000);
assert.equal(paymentPollDelay(8), 30000);
assert.equal(paymentPollingFinished("successful"), true);
assert.equal(paymentPollingFinished("failed"), true);
assert.equal(paymentPollingFinished("processing"), false);
assert.equal(paymentPollingFinished("needs_review"), false);
const form = fs.readFileSync("src/components/job-desk/public-intake-form.tsx", "utf8");
assert.ok(!form.includes("setInterval(poll, 4000)"));
assert.ok(form.includes('if (status !== "successful" || busy) return;'));
assert.ok(form.includes("checkoutTokenRef.current = accessToken"));
const checkout = fs.readFileSync("src/lib/job-desk/checkout.ts", "utf8");
assert.ok(checkout.includes('(count ?? 0) >= 5'));
assert.ok(checkout.includes('["initiating", "processing", "needs_review"].includes(last.status)'));
console.log("Checkout tests passed: blocked storage, malformed cache, token reuse, bounded polling, paid-only reset and unchanged duplicate-prompt guards.");
